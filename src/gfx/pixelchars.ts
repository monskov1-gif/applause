// Лицо занимает столбцы 4..15, строки 3..15; шея 15..16; плечи с 17-й строки.
// Ключи: 1..4 — волосы перед лицом/телом (свет, база, тень, глубокая тень); a..d — те же тона за телом.
// Текстурные ключи (тон вычисляется по сетке, со светом слева и тенью справа): L/l — прямые пряди,
// V/v — волна, C/c — кудри (заглавные — перед, строчные — за телом). k — золото, w — белое, r — цвет отделки.
// Строка «… *N» повторяется N раз.
import type { CharDef } from '../data/chars';

export interface HairSet { f: string[]; b: string[]; s: string[]; }
function g(src: string): string[] {
  const out: string[] = [];
  for (let line of src.split('\n')) { line = line.trim(); if (!line) continue; let n = 1; const m = line.match(/^(\S+)\s+\*(\d+)$/); if (m) { line = m[1]; n = +m[2]; } for (let i = 0; i < n; i++) out.push(line.padEnd(20, '.')); }
  return out;
}
const H = (f: string, b: string, s: string): HairSet => ({ f: g(f), b: g(b), s: g(s) });

