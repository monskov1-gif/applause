/** Причёска персонажа: своя маска (hairMask / id), иначе общая по style. */
export function hairMask(d: CharDef): HairSet {
  if (d.style === 'none') return NONE;
  const key = d.hairMask || d.id;
  if (HAIR[key]) return HAIR[key];
  if (GEN[key]) return GEN[key];
  if (GEN[d.style]) return GEN[d.style];
  const m = MAP[d.style]; if (m) return HAIR[m];
  return GEN.short;
}
